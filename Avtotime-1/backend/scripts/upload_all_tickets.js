async function uploadQuestions() {
  try {
    await mongoose.connect(process.env.MONGODB_URL);
    console.log("✓ Подключено к БД");

    // Удалим старые вопросы билетов 6-10
    await DrivingQuestion.deleteMany({ ticketNumber: { $in: [6, 7, 8, 9, 10] } });
    console.log("✓ Очищены вопросы билетов 6-10");

    // Добавим новые вопросы
    const result = await DrivingQuestion.insertMany(ticketsData);
    console.log(`✓ Добавлено ${result.length} вопросов для билетов 6-10`);

    // Получим общую статистику
    const totalQuestions = await DrivingQuestion.countDocuments();
    const ticketStats = await DrivingQuestion.aggregate([
      { $group: { _id: "$ticketNumber", count: { $sum: 1 } } },
      { $sort: { _id: 1 } }
    ]);

    console.log(`\n✓ Всего вопросов в БД: ${totalQuestions}`);
    console.log("\nВопросы по билетам:");
    ticketStats.forEach(stat => {
      console.log(`  Билет ${stat._id}: ${stat.count} вопросов`);
    });

    console.log("\n✓ Загрузка завершена успешно!");
    process.exit(0);
  } catch (error) {
    console.error("✗ Ошибка:", error.message);
    process.exit(1);
  }
}

uploadQuestions();
