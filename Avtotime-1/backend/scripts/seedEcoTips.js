const run = async () => {
  const url = process.env.MONGODB_URL;
  if (!url) throw new Error("MONGODB_URL не задан");

  await mongoose.connect(url);

  // Автор нужен схемой: берём администратора, иначе — самого раннего
  // пользователя. Без пользователей в базе сеять некому.
  const author =
    (await User.findOne({ isAdmin: true }).select("_id").lean())
    || (await User.findOne().sort({ createdAt: 1 }).select("_id").lean());

  if (!author) throw new Error("В базе нет ни одного пользователя — некого назначить автором");

  let created = 0;
  let skipped = 0;

  for (const tip of TIPS) {
    const exists = await MarketEcoTip.findOne({ title: tip.title }).select("_id").lean();
    if (exists) {
      skipped += 1;
      continue;
    }

    await MarketEcoTip.create({
      // id — числовой ключ схемы; берём время с запасом на совпадения.
      id: Date.now() + created,
      title: tip.title,
      description: tip.description,
      category: tip.category,
      image: tip.image || "",
      author: author._id,
      moderationStatus: "approved",
      moderationProvider: "seed",
      moderationCheckedAt: new Date(),
    });
    created += 1;
  }

  console.log(JSON.stringify({ created, skipped, total: TIPS.length }));
  await mongoose.disconnect();
};

run().catch(async (error) => {
  console.error("seedEcoTips:", error.message);
  await mongoose.disconnect().catch(() => {});
  process.exitCode = 1;
});
